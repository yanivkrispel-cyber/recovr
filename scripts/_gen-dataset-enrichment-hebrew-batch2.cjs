function cleanNameEn(name) {
  return name
    .replace(/\s*\((male|female)\)\s*/gi, '')
    .replace(/\s*v\.?\s*2\b/gi, '')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

function modifierSuffix(name) {
  const n = name.toLowerCase();
  const hits = [];
  for (const [re, he] of MODIFIERS) {
    if (re.test(n)) hits.push(he);
  }
  return hits.length ? ' ' + hits.join(' ') : '';
}

function movementPhrase(name, target) {
  const n = name.toLowerCase();
  for (const [kw, fn] of MOVEMENTS) {
    if (n.includes(kw)) {
      const phrase = fn(target, n);
      if (phrase) return phrase;
    }
  }
  return null;
}

function synthesize(rec) {
  const key = rec.name.toLowerCase().trim();
  if (OTHER[key]) return { name_he: OTHER[key][0], sentence_he: OTHER[key][1] };

  const movement = movementPhrase(rec.name, rec.target);
  if (!movement) return null;

  const equip = EQUIPMENT_HE[rec.equipment] || rec.equipment;
  const suffix = modifierSuffix(rec.name);
  const name_he = `${movement}${suffix} עם ${equip}`.replace(/\s+/g, ' ').trim();
  const sentence_he = `לבצע ${movement}${suffix} תוך שימוש ב${equip}, בתנועה מבוקרת ורצופה, ולחזור למצב ההתחלה בשליטה.`;
  return { name_he, sentence_he };
}

const rem = JSON.parse(fs.readFileSync('scripts/_remaining_1038.json', 'utf8'));
const out = [];
const unresolved = [];
for (const rec of rem) {
  const result = synthesize(rec);
  if (!result) {
    unresolved.push(rec.id + ' :: ' + rec.name);
    continue;
  }
  out.push([rec.id, result.name_he, result.sentence_he]);
}

